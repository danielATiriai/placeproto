import { chromium } from '@playwright/test'
const url = 'https://script.google.com/macros/s/AKfycbxlr_Af4gyBFM0swKgr1E05rJjndda6fUF4f3Kyw84ZsIqjbl7JJRTz9olG4iEZQjXBjA/exec'
const body = new URLSearchParams({ form: 'placeproto', t: String(Date.now() - 10000), website: '', name: 'Claude CI probe (delete me)', email: 'probe@placeproto.org', segment: 'other', organization: 'CI probe', message: 'Diagnosing the Not sent state; safe to delete.', ajax: '1' })
const r = await fetch(url, { method: 'POST', body, headers: { Accept: 'application/json' }, redirect: 'manual' })
console.log('node POST', r.status, r.headers.get('location'))
const r2 = await fetch(url, { method: 'POST', body, headers: { Accept: 'application/json' } })
console.log('node followed', r2.status, r2.url, r2.headers.get('content-type'), 'acao=', r2.headers.get('access-control-allow-origin'), 'body=', (await r2.text()).slice(0, 200))

const browser = await chromium.launch()
const page = await browser.newPage()
page.on('response', (res) => console.log('browser response', res.status(), res.url().slice(0, 90), res.headers()['content-type'], 'acao=', res.headers()['access-control-allow-origin']))
page.on('requestfailed', (req) => console.log('browser requestfailed', req.url().slice(0, 90), req.failure()?.errorText))
page.on('console', (m) => console.log('console', m.type(), m.text()))
await page.goto('https://placeproto.org/')
await page.click('button[popovertarget=connect]')
await page.fill('[name=name]', 'Claude CI probe (delete me)')
await page.fill('[name=email]', 'probe@placeproto.org')
await page.check('input[name=segment][value=other]')
await page.fill('[name=organization]', 'CI probe')
await page.fill('[name=message]', 'Diagnosing the Not sent state from the live page; safe to delete.')
await page.waitForTimeout(3500)
await page.click('button[type=submit]')
await page.waitForTimeout(8000)
console.log('success visible', await page.locator('.form-success').isVisible(), 'error visible', await page.locator('.form-error').isVisible())
await browser.close()
